// Command importer copies EspOS workflows from the hosted EspOS backend folder
// (tables/, workflows/<code>/workflow.json + nodes/*.go, routes.json, workers/news) into this
// server: the declarations into internal/backend, each code node into its own Go package
// under internal/flows, the news worker into internal/jobs/newsjob, and a registry that
// ties node names to functions.
//
//	go run ./tools/importer -from ../web/backend
//
// A node is changed only where the hosted runtime differs from this one: its input and
// context arrive as arguments instead of wm.Input() / wm.Context(), and links to this
// server use its own address. Run it again after changing the hosted workflows.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"unicode/utf8"
)

var (
	from = flag.String("from", "", "the hosted project's backend folder (with tables/, workflows/, routes.json)")
	to   = flag.String("to", ".", "this repository's root")
)

func main() {
	flag.Parse()
	if *from == "" {
		log.Fatal("-from is required")
	}
	backend := filepath.Join(*to, "internal", "backend")
	flows := filepath.Join(*to, "internal", "flows")
	must(os.RemoveAll(filepath.Join(backend, "workflows")))
	must(os.RemoveAll(filepath.Join(backend, "tables")))
	must(os.RemoveAll(flows))

	wfs, _ := filepath.Glob(filepath.Join(*from, "workflows", "*", "workflow.json"))
	skip := skipSet(wfs, routedWorkflows(filepath.Join(*from, "routes.json")))
	importRoutes(filepath.Join(*from, "routes.json"), filepath.Join(backend, "routes.json"), skip)
	all, _ := filepath.Glob(filepath.Join(*from, "tables", "*.json"))
	var tables []string
	for _, t := range all {
		if retired[strings.TrimSuffix(filepath.Base(t), ".json")] {
			continue
		}
		tables = append(tables, t)
		copyFile(t, filepath.Join(backend, "tables", filepath.Base(t)))
	}

	type reg struct{ key, alias, pkg string }
	var regs []reg
	skipped := 0
	for _, wf := range wfs {
		code := filepath.Base(filepath.Dir(wf))
		if why := skip[code]; why != "" {
			log.Printf("skipped workflow %s (%s)", code, why)
			skipped++
			continue
		}
		if stand, ok := standIns[code]; ok {
			dst := filepath.Join(backend, "workflows", code, "workflow.json")
			must(os.MkdirAll(filepath.Dir(dst), 0o755))
			must(os.WriteFile(dst, []byte(stand), 0o644))
			log.Printf("workflow %s: this server's own stand-in, not the hosted one", code)
			continue
		}
		raw, err := os.ReadFile(wf)
		must(err)
		dst := filepath.Join(backend, "workflows", code, "workflow.json")
		must(os.MkdirAll(filepath.Dir(dst), 0o755))
		must(os.WriteFile(dst, []byte(scrub(string(portSpeech(code, raw)))), 0o644))
		nodes, _ := filepath.Glob(filepath.Join(filepath.Dir(wf), "nodes", "*.go"))
		for _, n := range nodes {
			stem := strings.TrimSuffix(filepath.Base(n), ".go")
			src, err := os.ReadFile(n)
			must(err)
			out := portAssistant(code, stem, portNode(code, stem, string(src)))
			dst := filepath.Join(flows, code, stem, stem+".go")
			writeGo(dst, out)
			regs = append(regs, reg{code + "/" + stem, code + "_" + stem, "espos/internal/flows/" + code + "/" + stem})
		}
	}
	sort.Slice(regs, func(i, j int) bool { return regs[i].key < regs[j].key })
	var b strings.Builder
	b.WriteString("// Code generated by tools/importer. DO NOT EDIT.\n\n// Package flows maps each workflow code node to its Go function.\npackage flows\n\nimport (\n\t\"espos/internal/engine\"\n")
	for _, r := range regs {
		fmt.Fprintf(&b, "\t%s %q\n", r.alias, r.pkg)
	}
	b.WriteString(")\n\n// Nodes is every code node, by \"<workflow>/<node>\".\nvar Nodes = map[string]engine.NodeFunc{\n")
	for _, r := range regs {
		fmt.Fprintf(&b, "\t%q: %s.Run,\n", r.key, r.alias)
	}
	b.WriteString("}\n")
	writeGo(filepath.Join(flows, "registry.go"), b.String())

	importWorker(filepath.Join(*from, "workers", "news"), filepath.Join(*to, "internal", "jobs", "newsjob"))
	tables = dropUnused(tables, filepath.Join(backend, "tables"), filepath.Join(*to, "internal"), filepath.Join(*to, "cmd"))
	checkPrivate(backend, flows, filepath.Join(*to, "internal", "jobs", "newsjob"))
	fmt.Printf("imported %d tables, %d workflows (%d skipped), %d code nodes\n", len(tables), len(wfs)-skipped, skipped, len(regs))
}

// dropUnused removes the imported tables that no code here names (a quoted "<code>" in a Go file
// or a workflow under dirs): tables of a hosted feature still being built, before its routes.
func dropUnused(tables []string, dir string, dirs ...string) []string {
	var src strings.Builder
	for _, d := range dirs {
		filepath.WalkDir(d, func(path string, e os.DirEntry, err error) error {
			if err != nil || e.IsDir() || strings.HasPrefix(path, dir) {
				return err
			}
			if strings.HasSuffix(path, ".go") || strings.HasSuffix(path, ".json") {
				b, err := os.ReadFile(path)
				must(err)
				src.Write(b)
			}
			return nil
		})
	}
	all := src.String()
	var kept []string
	for _, t := range tables {
		code := strings.TrimSuffix(filepath.Base(t), ".json")
		if !strings.Contains(all, `"`+code+`"`) && !strings.Contains(all, `\"`+code+`\"`) {
			log.Printf("skipped table %s (nothing here uses it yet)", code)
			must(os.Remove(filepath.Join(dir, filepath.Base(t))))
			continue
		}
		kept = append(kept, t)
	}
	return kept
}

// The hosted sign-up's account events. This server has one account, set by ESPOS_USER and
// ESPOS_PASSWORD: nobody registers, verifies an address or resets a password, so the workflows
// that mail on these events (event_trigger → smtp_send) have nothing to start them.
var accountEvents = map[string]bool{
	"user.registered":             true,
	"user.verification_requested": true,
	"password.reset_requested":    true,
	"user.deleted":                true,
}

// skipReason says why a hosted workflow is left out, or "" to import it:
//   - it mails on one of the account events above;
//   - it answers HTTP (http_in) but no route in routes.json runs it: a draft or a temporary
//     probe on the hosted site, which may call services this server knows nothing about;
//   - it reads a hosted secret this server cannot fill ({{ secret.* }} other than the dog assistant's AI model
//     and speech service, which come from the environment here: assistant.go).
//
// A workflow on another event stops the import: the engine runs no event_trigger yet.
func skipReason(wf, code string, routed map[string]bool) string {
	raw, err := os.ReadFile(wf)
	must(err)
	var doc struct {
		Draft struct {
			Nodes []struct {
				Type   string         `json:"type"`
				Config map[string]any `json:"config"`
			} `json:"nodes"`
		} `json:"draft"`
	}
	must(json.Unmarshal(raw, &doc))
	if strings.HasPrefix(code, "admin_") && !keptAdmin[code] && standIns[code] == "" {
		return "the hosted service's administration (users, roles, licences, stock); this server has one account"
	}
	for _, n := range doc.Draft.Nodes {
		switch n.Type {
		case "event_trigger":
			ev, _ := n.Config["event"].(string)
			if !accountEvents[ev] {
				log.Fatalf("%s: event_trigger on %q is not supported here: add it to internal/engine or skip it in the importer", wf, ev)
			}
			return "e-mail on the hosted sign-up's " + ev + "; this server has one account and no sign-up"
		case "http_in":
			if !routed[code] {
				return "no route runs it: a draft or a probe on the hosted site"
			}
		}
	}
	if name := hostedSecret(raw); name != "" {
		return "needs the hosted service's secret " + name + "; this server has none"
	}
	if name := nodesNeedSecret(filepath.Dir(wf)); name != "" {
		return "a code node needs the hosted service's secret " + name + "; this server has none"
	}
	return ""
}

// The admin workflows this server keeps (its one account's own page needs them); every other admin_* is the hosted
// service's administration: its guards (admin_require_active, admin_device_active, admin_lic) are dropped from the
// routes, so here nothing is blocked or licensed (the device then locks nothing, docs: s3/docs/lock.md).
var keptAdmin = map[string]bool{"admin_me": true, "admin_sign": true}

// Stand-ins for hosted functions other workflows call, in this server's terms. admin_lic_core is the hosted licence
// (trials, paid content, AI turns): here every device is unlicensed and may use the AI it is configured with, as
// s3/docs/lock.md says a device without a licence does (the sessions app calls it before an AI turn).
var standIns = map[string]string{
	"admin_lic_core": `{"code":"admin_lic_core","draft":{"nodes":[
  {"id":"in","type":"function_in","config":{"inputs":["device_id","user_id"],"optional":["hwid","mac4","start","use_ai"]}},
  {"id":"out","type":"return","config":{"data":{"lic":null,"lic_ms":0,"ai_ok":true,"locked":"","buy_url":"","trial":false}}}],
 "edges":[{"from":"in","to":"out"}]}}
`,
}

// nodesNeedSecret: the first hosted secret a code node of the workflow reads that this server cannot fill, or "".
func nodesNeedSecret(dir string) string {
	nodes, _ := filepath.Glob(filepath.Join(dir, "nodes", "*.go"))
	for _, n := range nodes {
		b, err := os.ReadFile(n)
		must(err)
		if name := hostedSecret(b); name != "" {
			return name
		}
	}
	return ""
}

// skipSet is every workflow left out, with the reason: skipReason's, then (until nothing changes) every
// workflow that calls one left out (call_workflow), since it could not run here.
func skipSet(wfs []string, routed map[string]bool) map[string]string {
	skip := map[string]string{}
	calls := map[string][]string{}
	for _, wf := range wfs {
		code := filepath.Base(filepath.Dir(wf))
		if why := skipReason(wf, code, routed); why != "" {
			skip[code] = why
		}
		raw, err := os.ReadFile(wf)
		must(err)
		var doc struct {
			Draft struct {
				Nodes []struct {
					Type   string         `json:"type"`
					Config map[string]any `json:"config"`
				} `json:"nodes"`
			} `json:"draft"`
		}
		must(json.Unmarshal(raw, &doc))
		for _, n := range doc.Draft.Nodes {
			if n.Type == "call_workflow" {
				if w, _ := n.Config["workflow"].(string); w != "" {
					calls[code] = append(calls[code], w)
				}
			}
		}
	}
	for changed := true; changed; {
		changed = false
		for code, callees := range calls {
			if skip[code] != "" {
				continue
			}
			for _, c := range callees {
				if skip[c] != "" {
					skip[code] = "calls " + c + ", which is left out"
					changed = true
					break
				}
			}
		}
	}
	return skip
}

// routedWorkflows is every workflow a hosted route names, published or not.
func routedWorkflows(path string) map[string]bool {
	raw, err := os.ReadFile(path)
	must(err)
	var hosted []struct {
		Workflow     string `json:"workflow"`
		WorkflowCode string `json:"workflow_code"`
	}
	must(json.Unmarshal(raw, &hosted))
	out := map[string]bool{}
	for _, r := range hosted {
		out[r.Workflow] = true
		out[r.WorkflowCode] = true
	}
	return out
}

// Strings that must never reach the public repository: the hosted service's domains, storage
// paths and platform, local folders and e-mail addresses. The names are spelled in pieces so
// this file passes the same check.
var private = regexp.MustCompile(`(?i)` + strings.Join([]string{
	`3s` + `web`, `web` + `mati`, `/Us` + `ers/`, `~/pro` + `jects/`, `\bHi` + `ếu\b`, `api\.esp` + `os\.dev`, `/storage/bb/`,
	`[a-z0-9._%+-]+@[a-z0-9-]+(\.[a-z0-9-]+)*\.[a-z]{2,}`,
}, "|"))

// The product's former name: nothing in the repo may carry it.
var formerName = regexp.MustCompile(`(?i)ink` + `desk`)

// checkPrivate fails the import when a private string slipped through, and lists every line
// that still carries the former product name.
func checkPrivate(dirs ...string) {
	var leaks, former []string
	for _, dir := range dirs {
		filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
			if err != nil || d.IsDir() {
				return err
			}
			b, err := os.ReadFile(path)
			must(err)
			if !utf8.Valid(b) || bytes.ContainsRune(b, 0) {
				return nil
			}
			for i, line := range strings.Split(string(b), "\n") {
				at := fmt.Sprintf("%s:%d: %s", path, i+1, strings.TrimSpace(line))
				if private.MatchString(line) {
					leaks = append(leaks, at)
				}
				if formerName.MatchString(line) {
					former = append(former, at)
				}
			}
			return nil
		})
	}
	for _, f := range former {
		log.Printf("former product name: %s", f)
	}
	if len(leaks) > 0 {
		log.Fatalf("private strings imported, fix the hosted source or a rewrite here:\n%s", strings.Join(leaks, "\n"))
	}
}

// scrub rewrites references that only make sense in the hosted project, in every imported file.
func scrub(s string) string {
	// The hosted docs/<name>-api.md is this repository's docs/device-api.md.
	s = docRef.ReplaceAllString(s, "docs/device-api.md")
	// Examples written with the owner's own name get a made-up one, and one quoting the owner's own session text a
	// neutral one.
	s = strings.ReplaceAll(s, "Tài khoản "+"Amazon:", "Tài khoản:") // in pieces so this file passes the repository checks
	return strings.ReplaceAll(s, ownerName, "Lan")
}

var docRef = regexp.MustCompile(`docs/[a-z0-9]+-api\.md`)

// The owner's given name, spelled in pieces so this file passes the repository's own checks.
var ownerName = "Hi" + "ếu"

// Tables the hosted site keeps for old data but nothing here uses.
var retired = map[string]bool{"tasks": true, "vocab": true}

// Route is one HTTP route: who may call it and the workflow that answers.
type Route struct {
	Method   string   `json:"method"`
	Path     string   `json:"path"`
	Auth     string   `json:"auth"`
	Guards   []string `json:"guards,omitempty"`
	Workflow string   `json:"workflow"`
	PerMin   int      `json:"rate_limit_per_min,omitempty"`
}

func importRoutes(src, dst string, skip map[string]string) {
	dropped := map[string]bool{}
	defer func() {
		var names []string
		for g := range dropped {
			names = append(names, g)
		}
		sort.Strings(names)
		if len(names) > 0 {
			log.Printf("guards left out of the routes (their workflows are left out): %s", strings.Join(names, ", "))
		}
	}()
	raw, err := os.ReadFile(src)
	must(err)
	var hosted []struct {
		Method       string   `json:"method"`
		Path         string   `json:"path"`
		AuthMode     string   `json:"auth_mode"`
		Guards       []string `json:"guards"`
		Workflow     string   `json:"workflow"`
		WorkflowCode string   `json:"workflow_code"`
		Published    *bool    `json:"is_published"`
		PerMin       *int     `json:"rate_limit_per_min"`
	}
	must(json.Unmarshal(raw, &hosted))
	var out []Route
	for _, r := range hosted {
		if r.Published != nil && !*r.Published {
			continue
		}
		// Routes for the hosted platform's API keys (the store's publishing tool) have no use here:
		// this server has one account and no API keys.
		if r.AuthMode == "api_key" {
			log.Printf("skipped %s %s (api_key route of the hosted store)", r.Method, r.Path)
			continue
		}
		wf := r.Workflow
		if wf == "" {
			wf = r.WorkflowCode
		}
		if skip[wf] != "" {
			log.Printf("skipped %s %s (its workflow %s is left out)", r.Method, r.Path, wf)
			continue
		}
		var guards []string
		open := ""
		for _, g := range r.Guards {
			if skip[g] != "" {
				if !strings.HasPrefix(g, "admin_") {
					open = g // a check this route relies on: without it the route would be open, so it goes
					break
				}
				dropped[g] = true
				continue
			}
			guards = append(guards, g)
		}
		if open != "" {
			log.Printf("skipped %s %s (its guard %s is left out)", r.Method, r.Path, open)
			continue
		}
		rt := Route{Method: r.Method, Path: r.Path, Auth: r.AuthMode, Guards: guards, Workflow: wf}
		if r.PerMin != nil {
			rt.PerMin = *r.PerMin
		}
		out = append(out, rt)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Path+out[i].Method < out[j].Path+out[j].Method })
	b, err := json.MarshalIndent(out, "", "  ")
	must(err)
	must(os.MkdirAll(filepath.Dir(dst), 0o755))
	must(os.WriteFile(dst, append(b, '\n'), 0o644))
}

var (
	header    = regexp.MustCompile(`(?m)^// [a-z]+:node .*\n`) // the hosted platform's node header
	importOne = regexp.MustCompile(`(?m)^import "wm"$`)
	importIn  = regexp.MustCompile(`(?m)^(\s*)"wm"$`)
	runSig    = regexp.MustCompile(`func Run\(\) map\[string\]any \{`)
	// The hosted API's address as a node's fallback host: api.<domain> or api-<name>.<domain>.
	hostedHost = regexp.MustCompile(`host = "api[.-][a-z0-9.-]+"`)
	// The news worker's imports of its own module, whatever the hosted module is called.
	workerImport = regexp.MustCompile(`"[a-z0-9]+/news/news"`)
	workerJob    = regexp.MustCompile(`"[a-z0-9]+/news/wmjob"`)
)

func portNode(code, stem, src string) string {
	s := header.ReplaceAllString(src, fmt.Sprintf("// Workflow %s, node %s (imported by tools/importer).\n", code, stem))
	s = strings.Replace(s, "package wmnode", "package "+stem, 1)
	s = importOne.ReplaceAllString(s, `import "espos/internal/wm"`)
	s = importIn.ReplaceAllString(s, `$1"espos/internal/wm"`)
	s = runSig.ReplaceAllString(s, "func Run(wmIn, wmCtx map[string]any) map[string]any {")
	s = inRun(s, func(body string) string {
		body = strings.ReplaceAll(body, "wm.Input()", "wmIn")
		return strings.ReplaceAll(body, "wm.Context()", "wmCtx")
	})
	// Links back to this server: its own scheme and host, not the hosted API's.
	s = strings.ReplaceAll(s, `host := wm.Str(in["host"])`, `host := wm.PublicBase(wm.Str(in["host"]))`)
	s = hostedHost.ReplaceAllString(s, `host = wm.PublicBase("")`)
	s = strings.ReplaceAll(s, `fmt.Sprintf("https://%s/v1/`, `fmt.Sprintf("%s/v1/`)
	// Firmware bundles added with `espos firmware add` are stored as paths on this server.
	s = strings.ReplaceAll(s, `"url": wm.Str(f["url"])`, `"url": wm.AbsURL(wm.Str(in["host"]), wm.Str(f["url"]))`)
	// The hosted package store's catalog: here it is whatever ESPOS_PKG_CATALOG names (none: no packages offered).
	s = regexp.MustCompile(`const catalogURL = "https?://[^"]+/apps/catalog\.json"`).
		ReplaceAllString(s, `var catalogURL = wm.PkgCatalogURL()`)
	// The store's catalogs that app_manifests_tick reads: here the ones ESPOS_PKG_CATALOG names.
	s = regexp.MustCompile(`var catalogs = \[\]string\{(\s*"https?://[^"]+/catalog\.json",)+\s*\}`).
		ReplaceAllString(s, `var catalogs = wm.PkgCatalogURLs()`)
	// The API address handed to a client (desktop_token): this server's own.
	s = regexp.MustCompile(`api := "https://api[.-][a-z0-9.-]+"\n\t+if h := strings\.TrimSpace\(wm\.Str\(in\["host"\]\)\); hostRe\.MatchString\(h\) \{\n\t+api = "https://" \+ h[^\n]*\n\t+\}`).
		ReplaceAllString(s, `api := wm.PublicBase(strings.TrimSpace(wm.Str(in["host"]))) // this server's own address`)
	if !strings.Contains(s, "wm.") {
		s = regexp.MustCompile(`(?m)^\s*"espos/internal/wm"\n`).ReplaceAllString(s, "")
		s = strings.Replace(s, `import "espos/internal/wm"`, "", 1)
	}
	// Outside Run, wm.Context() is this server's stand-in (a fresh run id); the input is only Run's.
	if strings.Contains(s, "wm.Input") {
		log.Fatalf("%s/%s: wm.Input outside Run", code, stem)
	}
	return s
}

// inRun applies f to the body of func Run only (from its signature to the first closing brace at column 0).
func inRun(s string, f func(string) string) string {
	i := strings.Index(s, "func Run(")
	if i < 0 {
		return s
	}
	j := strings.Index(s[i:], "\n}\n")
	if j < 0 {
		return s[:i] + f(s[i:])
	}
	j += i
	return s[:i] + f(s[i:j]) + s[j:]
}

func importWorker(src, dst string) {
	if _, err := os.Stat(filepath.Join(src, "main.go")); err != nil {
		return
	}
	must(os.RemoveAll(dst))
	main, err := os.ReadFile(filepath.Join(src, "main.go"))
	must(err)
	s := string(main)
	s = regexp.MustCompile(`(?m)^//go:build .*\n\n?`).ReplaceAllString(s, "")
	s = strings.Replace(s, "package main", "package newsjob", 1)
	// The hosted worker is its own module (espos/news, or the product's former name before the rename).
	s = workerImport.ReplaceAllString(s, `"espos/internal/jobs/newsjob/news"`)
	s = workerJob.ReplaceAllString(s, `"espos/internal/wmjob"`)
	s = strings.Replace(s, "func main() {", "// Main runs one job (its input comes from wmjob.Input).\nfunc Main() {", 1)
	s = strings.ReplaceAll(s, "os.Exit(2)", "panic(wmjob.ErrAbort)")
	if !regexp.MustCompile(`\bos\.`).MatchString(s) {
		s = regexp.MustCompile(`(?m)^\s*"os"\n`).ReplaceAllString(s, "")
	}
	writeGo(filepath.Join(dst, "job.go"), s)
	files, _ := filepath.Glob(filepath.Join(src, "news", "*"))
	for _, f := range files {
		if fi, err := os.Stat(f); err == nil && fi.IsDir() {
			sub, _ := filepath.Glob(filepath.Join(f, "*"))
			for _, g := range sub {
				copyFile(g, filepath.Join(dst, "news", filepath.Base(f), filepath.Base(g)))
			}
			continue
		}
		copyFile(f, filepath.Join(dst, "news", filepath.Base(f)))
	}
}

func writeGo(path, src string) {
	out, err := format.Source([]byte(scrub(src)))
	if err != nil {
		log.Fatalf("%s: %v", path, err)
	}
	must(os.MkdirAll(filepath.Dir(path), 0o755))
	must(os.WriteFile(path, out, 0o644))
}

func copyFile(src, dst string) {
	b, err := os.ReadFile(src)
	must(err)
	if utf8.Valid(b) && !bytes.ContainsRune(b, 0) { // text, not a font or picture
		b = []byte(scrub(string(b)))
	}
	must(os.MkdirAll(filepath.Dir(dst), 0o755))
	must(os.WriteFile(dst, b, 0o644))
}

func must(err error) {
	if err != nil {
		log.Fatal(err)
	}
}
