"""PawBoop's app icon from a picture of Biscuit (the pack's own frame) on a warm squircle, in the look of
tools/art/make_art.py: 52 px icon with a soft shadow in a 60 px image, plus 40 and 28 px, RGB565A8.
  python3 tools/pawboop/make_icon.py   (from s3/) -> src/pet/pet_icon.c / .h
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

from pbs import Pack

ROOT = Path(__file__).resolve().parents[2]
S = 4  # supersampling
CLIP, FRAME = "nudge", 12  # a big smiling face


def squircle(size, radius, top, bottom):
    """A rounded square with a vertical gradient (RGBA)."""
    grad = Image.new("RGBA", (size, size))
    d = ImageDraw.Draw(grad)
    for y in range(size):
        t = y / (size - 1)
        d.line([(0, y), (size, y)], fill=tuple(int(a + (b - a) * t) for a, b in zip(top, bottom)) + (255,))
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, size - 1, size - 1], radius, fill=255)
    grad.putalpha(mask)
    return grad, mask


def icon(px):
    n = px * S
    ic, mask = squircle(n, 14 * n // 52, (255, 243, 214), (255, 196, 140))
    dog, _ = Pack(ROOT / "sim/data/pawboop/biscuit_M.pbs").picture(CLIP, FRAME)
    x0, y0, x1, y1 = dog.getbbox()
    w = x1 - x0
    side = int(w * 1.04)  # head and shoulders: a square from the top of her ears
    crop = dog.crop((x0 + w // 2 - side // 2, y0 - int(side * 0.06), x0 + w // 2 + side // 2, y0 + int(side * 0.94)))
    crop = crop.resize((int(n * 0.94), int(n * 0.94)), Image.LANCZOS)
    layer = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    layer.alpha_composite(crop, ((n - crop.size[0]) // 2, n - crop.size[1] + n // 40))
    a = Image.composite(layer.getchannel("A"), Image.new("L", (n, n), 0), mask)  # clipped to the squircle
    layer.putalpha(a)
    ic.alpha_composite(layer)
    return ic


def with_shadow(ic52):
    """The 52 px icon centred in 60 px with box-shadow 0 2px 5px rgba(0,0,0,.28) (as make_art.py)."""
    n = 60 * S
    out = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    sh = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    m = Image.new("L", (n, n), 0)
    o = 4 * S
    ImageDraw.Draw(m).rounded_rectangle([o, o + 2 * S, o + 52 * S - 1, o + 2 * S + 52 * S - 1], 14 * S, fill=int(255 * 0.28))
    m = m.filter(ImageFilter.GaussianBlur(2.5 * S))
    sh.putalpha(m)
    out.alpha_composite(sh)
    out.alpha_composite(ic52, (o, o))
    return out


def rgb565a8(im):
    color, alpha = bytearray(), bytearray()
    for r, g, b, a in im.getdata():
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        color += bytes((v & 0xFF, v >> 8))
        alpha.append(a)
    return bytes(color + alpha)


def emit(out, name, im):
    w, h = im.size
    data = rgb565a8(im)
    out.append(f"static const uint8_t {name}_px[] = {{")
    for i in range(0, len(data), 32):
        out.append("  " + ",".join(str(b) for b in data[i:i + 32]) + ",")
    out.append("};")
    out.append(f"const lv_image_dsc_t {name} = {{")
    out.append(f"  .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .flags = 0, .w = {w}, .h = {h}, .stride = {w * 2}, .reserved_2 = 0}},")
    out.append(f"  .data_size = {len(data)}, .data = {name}_px, .reserved = NULL,")
    out.append("};")


def main():
    big = icon(52)
    out = ["// Generated by tools/pawboop/make_icon.py: PawBoop's app icon (Biscuit, from the picture pack), RGB565A8.",
           "#include <lvgl.h>", ""]
    emit(out, "ic_pet_52", with_shadow(big).resize((60, 60), Image.LANCZOS))
    for n in (40, 28):
        emit(out, f"ic_pet_{n}", big.resize((n, n), Image.LANCZOS))
    (ROOT / "src/pet/pet_icon.c").write_text("\n".join(out) + "\n")
    (ROOT / "src/pet/pet_icon.h").write_text(
        "#pragma once\n// Generated by tools/pawboop/make_icon.py.\n#include <lvgl.h>\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n"
        "extern const lv_image_dsc_t ic_pet_52;  // 60x60 with its shadow (home, dock)\n"
        "extern const lv_image_dsc_t ic_pet_40;\nextern const lv_image_dsc_t ic_pet_28;\n"
        "#ifdef __cplusplus\n}\n#endif\n")
    prev = Image.new("RGBA", (200, 70), (33, 26, 84, 255))  # on the default wallpaper colour, to eyeball
    prev.alpha_composite(with_shadow(big).resize((60, 60), Image.LANCZOS), (5, 5))
    prev.alpha_composite(big.resize((40, 40), Image.LANCZOS), (80, 15))
    prev.alpha_composite(big.resize((28, 28), Image.LANCZOS), (140, 21))
    return prev


if __name__ == "__main__":
    import sys
    p = main()
    if len(sys.argv) > 1:
        p.resize((p.size[0] * 3, p.size[1] * 3), Image.NEAREST).save(sys.argv[1])
