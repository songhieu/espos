"""The symbol fonts: the few LVGL symbols the firmware uses, copied byte for byte (bitmaps, metrics, line height,
base line) out of LVGL's own lv_font_montserrat_14/20/28.c, which hold the whole Montserrat Latin set plus ~60
symbols (73 KB linked). They keep LVGL's names (lv_font_montserrat_N), so callers and the Ubuntu fonts' fallback
(fonts.cpp) do not change; lv_conf.h turns the full Montserrat fonts off and declares these.
Run from s3/: python3 tools/fontconv/make_symbols.py -> src/fonts/sym_14.c, sym_20.c, sym_28.c

Every LV_SYMBOL_* the firmware uses must be listed here (grep -rn LV_SYMBOL_ src sim apps): a missing one is drawn
as nothing.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LVGL = ROOT / ".pio/libdeps/s3desk/lvgl/src/font"
SIZES = [14, 20, 28]
# LV_SYMBOL_OK, CLOSE, UP (keyboard shift), CHARGE (status bar), BACKSPACE (keyboard)
SYMBOLS = [0xF00C, 0xF00D, 0xF077, 0xF0E7, 0xF55A]


def parse(px):
    s = (LVGL / f"lv_font_montserrat_{px}.c").read_text()
    bm = re.search(r"glyph_bitmap\[\] = \{(.*?)\n\};", s, re.S).group(1)
    # Glyphs in the bitmap appear in glyph id order, each after a /* U+XXXX */ comment.
    order, bitmaps = [], {}
    for m in re.finditer(r"/\* U\+([0-9A-F]+) .*? \*/(.*?)(?=/\* U\+|\Z)", bm, re.S):
        cp = int(m.group(1), 16)
        order.append(cp)
        bitmaps[cp] = [int(x, 16) for x in re.findall(r"0x[0-9a-f]+", m.group(2))]
    dsc = re.findall(r"\{\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), "
                     r"\.ofs_x = (-?\d+), \.ofs_y = (-?\d+)\}", s)
    assert len(dsc) == len(order) + 1, (px, len(dsc), len(order))  # + the reserved glyph 0
    glyphs = {cp: dsc[i + 1] for i, cp in enumerate(order)}
    metrics = {k: re.search(rf"\.{k} = (-?\d+)", s).group(1)
               for k in ("line_height", "base_line", "underline_position", "underline_thickness")}
    return bitmaps, glyphs, metrics


def emit(px):
    bitmaps, glyphs, m = parse(px)
    out = [f"// Generated by tools/fontconv/make_symbols.py: the LVGL symbols the firmware uses, copied from",
           f"// lv_font_montserrat_{px}.c (same bitmaps and metrics). Keeps LVGL's name; lv_conf.h declares it.",
           '#include "lvgl.h"', "", "static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {"]
    dsc = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,"]
    at = 0
    for cp in SYMBOLS:
        b = bitmaps[cp]
        _, adv, bw, bh, ox, oy = glyphs[cp]
        out.append(f"    /* U+{cp:04X} */")
        for i in range(0, len(b), 16):
            out.append("    " + ", ".join(f"0x{x:x}" for x in b[i:i + 16]) + ",")
        dsc.append(f"    {{.bitmap_index = {at}, .adv_w = {adv}, .box_w = {bw}, .box_h = {bh}, .ofs_x = {ox}, .ofs_y = {oy}}},")
        at += len(b)
    out += ["};", "", "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {"] + dsc + ["};", ""]
    offs = ", ".join(f"0x{cp - SYMBOLS[0]:x}" for cp in SYMBOLS)
    out += [f"static const uint16_t unicode_list[] = {{{offs}}};",
            "static const lv_font_fmt_txt_cmap_t cmaps[] = {",
            f"    {{.range_start = {SYMBOLS[0]}, .range_length = {SYMBOLS[-1] - SYMBOLS[0] + 1}, .glyph_id_start = 1,",
            f"     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(SYMBOLS)},",
            "     .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};", "",
            "static const lv_font_fmt_txt_dsc_t font_dsc = {",
            "    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL, .kern_scale = 0,",
            "    .cmap_num = 1, .bpp = 4, .kern_classes = 0, .bitmap_format = 0};", "",
            f"const lv_font_t lv_font_montserrat_{px} = {{",
            "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
            f"    .line_height = {m['line_height']}, .base_line = {m['base_line']}, .subpx = LV_FONT_SUBPX_NONE,",
            f"    .underline_position = {m['underline_position']}, .underline_thickness = {m['underline_thickness']},",
            "    .dsc = &font_dsc, .fallback = NULL, .user_data = NULL};"]
    path = ROOT / f"src/fonts/sym_{px}.c"
    path.write_text("\n".join(out) + "\n")
    print(f"{path.name}: {len(SYMBOLS)} symbols, {at} bytes of bitmaps")


for px in SIZES:
    emit(px)
